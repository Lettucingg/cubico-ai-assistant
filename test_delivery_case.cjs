  ui.load(fixture());
  assert.equal(d.querySelector('img'),null);
  assert.equal(field('fecha_confirmada').value,'');
  assert.equal(field('fecha_solicitada').value,'2026-11-17');
  assert.equal(field('ubicacion_url').required,false);
  assert.match(d.getElementById('delivery-case').textContent,/lunes y miércoles/);
  assert.match(d.getElementById('delivery-case').textContent,/2026-11-16/);
  d.querySelector('[data-use-shared]').click();
  assert.equal(field('ubicacion_url').value,'https://maps.app.goo.gl/shared');
  assert.equal(calls.length,0);
  edit('fecha_confirmada','2026-11-18');
  edit('direccion','Dirección revisada');
  ui.load(fixture('case-b','50700000002'));
  assert.notEqual(field('direccion').value,'Dirección revisada');
  ui.load({...fixture(),ficha_domicilio:{...fixture().ficha_domicilio,token:'new-server-token'}});
  assert.equal(field('direccion').value,'Dirección revisada');
  submit();await tick();
  assert.equal(calls[0][0],'/panel/solicitud/50700000001/domicilio');
  assert.equal(calls[0][1].token,'token-case-a','draft must retain original token for stale edit checks');
  assert.equal(calls[0][1].datos.fecha_confirmada,'2026-11-18');
  assert.equal(calls[0][1].datos.dia_solicitado,'martes');
  assert.equal(saved[0][0],'50700000001');
  ui.load(fixture());
  assert.notEqual(field('direccion').value,'Dirección revisada');
  response={ok:false,json:async()=>({detail:'El caso cambió; recarga'})};
  edit('referencias','Cambios que se deben conservar');submit();await tick();
  assert.match(d.querySelector('[data-delivery-status]').textContent,/cambió/);
  ui.load(fixture('case-b','50700000002'));ui.load(fixture());
  assert.equal(field('referencias').value,'Cambios que se deben conservar');
  d.querySelector('[data-delivery-reload]').click();
  assert.equal(reloaded[0],'50700000001');
  ui.load(fixture());assert.equal(field('referencias').value,'');
  let resolve;
  const pending=new Promise(r=>resolve=r);
  response={ok:true,json:()=>pending};
  edit('referencias','Saving');submit();
  assert.equal(field('referencias').disabled,true);
  ui.load(fixture('case-b','50700000002'));
  resolve({ficha:{revision:3}});await tick();
  assert.equal(field('direccion').value,fixture('case-b').ficha_domicilio.direccion);
  assert.equal(field('referencias').disabled,false);
  assert.equal(saved.at(-1)[0],'50700000001');
